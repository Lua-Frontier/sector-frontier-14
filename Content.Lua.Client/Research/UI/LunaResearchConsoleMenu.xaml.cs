    public void Recenter()
    {
        var view = ViewportSize();
        if (view.X < 8f || view.Y < 8f)
        {
            _pendingRecenter = true;
            return;
        }

        _zoom = 1f;
        ApplyHubRecenter(view);
        _pendingRecenter = false;
        ApplyCamera();
    }

    private void ApplyHubRecenter(Vector2 view)
    {
        var hubWorld = Vector2.Zero;
        if (!string.IsNullOrEmpty(_sectorId) && _positions.TryGetValue(_sectorId, out var hubPos))
            hubWorld = hubPos;

        var hubH = CardSize * _zoom;
        _offset = new Vector2(
            GraphPad - hubWorld.X * _zoom,
            view.Y * 0.5f - hubH * 0.5f - hubWorld.Y * _zoom + HubCenterBiasY);
    }

