    private void RebuildGraph()
    {
        DragContainer.RemoveAllChildren();
        _items.Clear();
        _positions.Clear();
        _visible.Clear();

        foreach (var id in CollectVisible())
            _visible.Add(id);

        LayoutGraph(_visible);

        foreach (var id in _visible)
        {
            if (!List.TryGetValue(id, out var availability))
                continue;
            if (!_prototype.TryIndex<TechnologyPrototype>(id, out var proto))
                continue;

            var item = new FancyResearchConsoleItem(
                proto,
                _research.GetTechnologyPrerequisites(_faction, proto),
                _sprite,
                availability);
            item.SetGraphCaptionVisible(false);
            item.ToolTip = Loc.GetString(proto.Name);
            item.SelectAction += SelectTech;
            item.IsSelected = id == CurrentTech;

            var project = FindProject(id);
            if (project is { Cost: > 0 })
                item.SetProjectProgress(project.Progress / (float) project.Cost);

            DragContainer.AddChild(item);
            _items[id] = item;
        }

        ApplySearchFilter();

        ApplyShellLayout();
        if (_pendingRecenter)
            Recenter();
        else
            ApplyCamera();

        if (CurrentTech != null &&
            _visible.Contains(CurrentTech.Value) &&
            _prototype.TryIndex(CurrentTech.Value, out var selected) &&
            List.TryGetValue(CurrentTech.Value, out var selectedAvail))
        {
            ApplyTechSelection(selected, selectedAvail, rightClick: false, allowToggleOff: false);
        }
    }

    private void ApplySearchFilter()
    {
        var query = _searchQuery;
        string? firstMatch = null;

        foreach (var (id, item) in _items)
        {
            var match = string.IsNullOrEmpty(query) || TechMatchesSearch(id, query);
            item.Visible = match;

            if (match && firstMatch == null && !string.IsNullOrEmpty(query))
                firstMatch = id;
        }

        if (firstMatch != null &&
            _positions.TryGetValue(firstMatch, out var pos) &&
            TechViewport.Size.X > 1f &&
            TechViewport.Size.Y > 1f)
        {
            var view = TechViewport.Size;
            _offset = new Vector2(
                view.X * 0.35f - pos.X * _zoom - CardSize * _zoom * 0.5f,
                view.Y * 0.45f - pos.Y * _zoom - CardSize * _zoom * 0.5f);
            ApplyCamera();
        }
    }

    private bool TechMatchesSearch(string id, string query)
    {
        if (!_prototype.TryIndex<TechnologyPrototype>(id, out var proto))
            return false;

        var name = Loc.GetString(proto.Name);
        if (name.Contains(query, StringComparison.OrdinalIgnoreCase))
            return true;

        if (proto.ID.Contains(query, StringComparison.OrdinalIgnoreCase))
            return true;

        return false;
    }

    private void LayoutGraph(HashSet<string> visible)
    {
        _positions.Clear();
        _worldMin = Vector2.Zero;
        _worldMax = new Vector2(CardSize, CardSize);
        if (visible.Count == 0)
            return;

        var needsAuto = new HashSet<string>();
        foreach (var id in visible)
        {
            if (!_prototype.TryIndex<TechnologyPrototype>(id, out var proto))
                continue;

            if (TryGetYamlPosition(proto, out var yamlPos))
                _positions[id] = yamlPos * GridSize;
            else
                needsAuto.Add(id);
        }

        if (needsAuto.Count > 0)
            LayoutAutoRanks(needsAuto, visible);

        _worldMin = new Vector2(float.MaxValue, float.MaxValue);
        _worldMax = new Vector2(float.MinValue, float.MinValue);
        foreach (var pos in _positions.Values)
        {
            _worldMin = Vector2.Min(_worldMin, pos);
            _worldMax = Vector2.Max(_worldMax, pos + new Vector2(CardSize, CardSize));
        }

        if (_positions.Count == 0)
        {
            _worldMin = Vector2.Zero;
            _worldMax = new Vector2(CardSize, CardSize);
        }
    }

    private bool TryGetYamlPosition(TechnologyPrototype proto, out Vector2 position)
    {
        if (_faction != null &&
            proto.FactionOverrides.TryGetValue(_faction.Value, out var ov) &&
            ov.Position is { } factionPos)
        {
            position = factionPos;
            return true;
        }

        if (proto.Position is { } pos)
        {
            position = pos;
            return true;
        }

        position = default;
        return false;
    }

    private void LayoutAutoRanks(HashSet<string> needsAuto, HashSet<string> visible)
    {
        var ranks = new Dictionary<string, int>();
        foreach (var id in needsAuto)
            ranks[id] = 0;

        for (var pass = 0; pass < needsAuto.Count + 2; pass++)
        {
            var changed = false;
            foreach (var id in needsAuto)
            {
                var next = 0;
                if (_prototype.TryIndex<TechnologyPrototype>(id, out var proto))
                {
                    var maxParent = 0;
                    var any = false;
                    foreach (var prereq in _research.GetTechnologyPrerequisites(_faction, proto))
                    {
                        if (!visible.Contains(prereq))
                            continue;

                        var parentRank = 0;
                        if (ranks.TryGetValue(prereq, out var r))
                            parentRank = r;
                        else if (_positions.TryGetValue(prereq, out var parentPos))
                            parentRank = Math.Max(0, (int) MathF.Round(parentPos.X / RankGap));

                        any = true;
                        maxParent = Math.Max(maxParent, parentRank);
                    }

                    if (any)
                        next = maxParent + 1;
                }

                if (ranks[id] == next)
                    continue;
                ranks[id] = next;
                changed = true;
            }

            if (!changed)
                break;
        }

        var maxRank = 0;
        foreach (var r in ranks.Values)
            maxRank = Math.Max(maxRank, r);

        for (var rank = 0; rank <= maxRank; rank++)
        {
            var ids = new List<string>();
            foreach (var (id, value) in ranks)
            {
                if (value == rank)
                    ids.Add(id);
            }

            ids.Sort((a, b) =>
            {
                var na = _prototype.TryIndex<TechnologyPrototype>(a, out var pa) ? Loc.GetString(pa.Name) : a;
                var nb = _prototype.TryIndex<TechnologyPrototype>(b, out var pb) ? Loc.GetString(pb.Name) : b;
                return string.Compare(na, nb, StringComparison.CurrentCulture);
            });

            if (rank == 1 && _sectorId != null && ids.Remove(_sectorId))
                ids.Insert(Math.Max(0, ids.Count / 2), _sectorId);

            if (ids.Count == 0)
                continue;

            var x = rank * RankGap;
            for (var i = 0; i < ids.Count; i++)
            {
                var y = (i - (ids.Count - 1) * 0.5f) * NodeGap;
                _positions[ids[i]] = new Vector2(x, y);
            }
        }
    }

    private Vector2 ViewportSize()
    {
        var w = TechViewport.Width;
        var h = TechViewport.Height;
        var scale = Math.Max(UIScale, 0.01f);
        if (w < 8f && TechViewport.PixelWidth > 0)
            w = TechViewport.PixelWidth / scale;
        if (h < 8f && TechViewport.PixelHeight > 0)
            h = TechViewport.PixelHeight / scale;
        return new Vector2(w, h);
    }

    private void SoftClampOffset()
    {
        if (_offset.X > GraphPad)
            _offset.X = GraphPad;
    }

    private void ApplyCamera()
    {
        if (_pendingRecenter)
        {
            var ready = ViewportSize();
            if (ready.X >= 8f && ready.Y >= 8f)
            {
                ApplyHubRecenter(ready);
                _pendingRecenter = false;
            }
        }

        SoftClampOffset();

        DragContainer.HorizontalAlignment = HAlignment.Left;
        DragContainer.VerticalAlignment = VAlignment.Top;
        LayoutContainer.SetPosition(DragContainer, Vector2.Zero);

        foreach (var (id, item) in _items)
        {
            if (!_positions.TryGetValue(id, out var pos))
                continue;
            LayoutContainer.SetPosition(item, pos * _zoom + _offset);
            item.SetScale(_zoom);
            item.SetGraphCaptionVisible(false);
        }

        var view = ViewportSize();
        var maxX = Math.Max(_worldMax.X * _zoom, CardSize * _zoom);
        var maxY = Math.Max(_worldMax.Y * _zoom, CardSize * _zoom);
        var minY = Math.Min(_worldMin.Y * _zoom, 0f);
        DragContainer.SetWidth = Math.Max(maxX + view.X + GraphPad, Math.Max(view.X, 1f));
        DragContainer.SetHeight = Math.Max(maxY - minY + view.Y + GraphPad, Math.Max(view.Y, 1f));
    }

    private void RelayoutCamera()
    {
        ApplyShellLayout();
        if (_visible.Count == 0)
            return;
        LayoutGraph(_visible);
        if (_pendingRecenter)
            Recenter();
        else
            ApplyCamera();
    }

