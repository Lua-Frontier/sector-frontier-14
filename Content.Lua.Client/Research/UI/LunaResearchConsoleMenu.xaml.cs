    public void SyncProjectVisuals()
    {
        foreach (var (id, item) in _items)
        {
            var project = FindProject(id);
            if (project is { Cost: > 0 })
                item.SetProjectProgress(project.Progress / (float) project.Cost);
            else
                item.SetProjectProgress(null);
        }

        if (CurrentTech == null || InfoContainer.ChildCount == 0)
            return;

        if (InfoContainer.GetChild(0) is not FancyTechnologyInfoPanel panel)
            return;

        List.TryGetValue(CurrentTech.Value, out var availability);
        panel.SyncProject(FindProject(CurrentTech.Value), availability);
    }

    public void UpdateInformationPanel(int points, bool rebuildTiers = true)
    {
        Points = points;
        var msg = new FormattedMessage();
        msg.AddMarkupOrThrow(Loc.GetString("research-console-menu-research-points-text", ("points", points)));
        ResearchAmountLabel.SetMessage(msg);

        if (!rebuildTiers)
            return;

        TierDisplayContainer.RemoveAllChildren();

        _entity.TryGetComponent(Entity, out TechnologyDatabaseComponent? database);

        IEnumerable<ProtoId<TechDisciplinePrototype>> disciplineIds =
            database is { SupportedDisciplines.Count: > 0 }
                ? database.SupportedDisciplines
                : new ProtoId<TechDisciplinePrototype>[]
                {
                    "NFEngineering", "NFMedical", "NFArsenal", "NFSalvage", "NFScience", "NFService", "Shiparmory",
                };

        foreach (var disciplineId in disciplineIds)
        {
            if (!_prototype.TryIndex(disciplineId, out TechDisciplinePrototype? discipline))
                continue;
            if (!_research.IsDisciplineFactionAllowed(Entity, discipline))
                continue;

            var completion = database != null
                ? _research.GetTierCompletionPercentage(Entity, database, discipline, _prototype)
                : 0;

            var texture = new TextureRect
            {
                TextureScale = new Vector2(2, 2),
                MinSize = new Vector2(16, 16),
                SetSize = new Vector2(16, 16),
                VerticalAlignment = VAlignment.Center,
                Stretch = TextureRect.StretchMode.KeepCentered,
                Texture = _sprite.Frame0(discipline.Icon),
            };
            var label = new RichTextLabel();
            label.SetMessage(Loc.GetString("research-console-discipline-percentage", ("perc", completion)));

            TierDisplayContainer.AddChild(new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 2,
                Children = { texture, label },
            });
        }

        var available = 0;
        var researched = 0;
        foreach (var (id, avail) in List)
        {
            if (!_visible.Contains(id))
                continue;
            available += 1;
            if (avail == ResearchAvailability.Researched)
                researched += 1;
        }

        ResearchedAmountLabel.Text = $"{researched}/{available}";
    }

