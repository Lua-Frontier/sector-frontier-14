        ApplyCamera();
    }

    protected override void MouseWheel(GUIMouseWheelEventArgs args) => ZoomWheel(args);

    private void OnWheel(GUIMouseWheelEventArgs args) => ZoomWheel(args);

    private void ZoomWheel(GUIMouseWheelEventArgs args)
    {
        if (args.Handled || args.Delta.Y == 0f)
            return;

        var viewportLocal = (args.RelativePixelPosition - PixelSize / 2f) / Math.Max(UIScale, 0.01f);
        var oldZoom = _zoom;
        _zoom = Math.Clamp(_zoom * MathF.Pow(ZoomStep, args.Delta.Y), MinZoom, MaxZoom);
        if (Math.Abs(_zoom - oldZoom) < 0.0001f)
            return;

        var worldBefore = (viewportLocal - _offset) / oldZoom;
        _offset = viewportLocal - worldBefore * _zoom;
        SoftClampOffset();
        ApplyCamera();
        args.Handle();
    }

