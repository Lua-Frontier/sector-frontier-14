    private void ApplyTechSelection(
        TechnologyPrototype proto,
        ResearchAvailability availability,
        bool rightClick,
        bool allowToggleOff)
    {
        InfoContainer.RemoveAllChildren();
        if (!_player.LocalEntity.HasValue)
            return;

        if (allowToggleOff && !rightClick && CurrentTech == proto.ID)
        {
            CurrentTech = null;
            foreach (var item in _items.Values)
                item.IsSelected = false;
            DragContainer.SetFocusTech(null);
            return;
        }

        CurrentTech = proto.ID;
        foreach (var item in _items.Values)
            item.IsSelected = item.Prototype.ID == CurrentTech;
        DragContainer.SetFocusTech(proto.ID);

        var hasAccess = _accessReader.IsAllowed(_player.LocalEntity.Value, Entity);
        var panel = new FancyTechnologyInfoPanel(proto, _faction, hasAccess, availability, _sprite, FindProject(proto.ID));
        panel.HorizontalExpand = true;
        panel.VerticalExpand = true;
        panel.BuyAction += args => OnTechnologyCardPressed?.Invoke(args.ID);
        panel.CancelAction += args => OnProjectCancelPressed?.Invoke(args.ID);
        LunaWindowStyle.ApplyCompactStyle(panel);
        InfoContainer.AddChild(panel);

        if (rightClick && panel.CanResearch && !panel.IsCancel)
            OnTechnologyCardPressed?.Invoke(proto.ID);
    }

    private void EnsureSector()
    {
        if (_sectorId != null &&
            _prototype.TryIndex<TechnologyPrototype>(_sectorId, out var selected) &&
            _research.IsTechnologyFactionAllowed(_faction, selected))
            return;

        _sectorId = null;
    }

    private void RebuildSectors()
    {
        EnsureSector();
        SectorsContainer.RemoveAllChildren();
    }

    private void RebuildQueue()
    {
        QueueContainer.RemoveAllChildren();
        if (_active.Count == 0 && _queued.Count == 0)
        {
            var empty = new Label
            {
                Text = Loc.GetString("research-console-auto-research-empty"),
                ClipText = true,
                HorizontalExpand = true,
            };
            LunaWindowStyle.StyleMuted(empty);
            QueueContainer.AddChild(empty);
            return;
        }

        foreach (var project in _active)
            QueueContainer.AddChild(MakeChip(project, Loc.GetString("research-console-auto-research-active"), true));
        foreach (var project in _queued)
            QueueContainer.AddChild(MakeChip(project, Loc.GetString("research-console-auto-research-waiting"), false));
    }

    private Control MakeChip(ResearchProjectUiState project, string status, bool progress)
    {
        var panel = new PanelContainer
        {
            MinWidth = 168,
            MinHeight = progress ? 48 : 36,
            PanelOverride = LunaWindowStyle.Panel(),
        };
        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(8, 4, 8, 4),
            SeparationOverride = 2,
        };
        var title = new Label { Text = project.Name, ClipText = true };
        LunaWindowStyle.StyleSecondary(title);
        box.AddChild(title);
        var subText = progress
            ? (project.Started
                ? Loc.GetString("research-console-auto-research-active-time",
                    ("done", project.PathDone), ("total", project.PathTotal), ("seconds", project.RemainingSeconds))
                : Loc.GetString("research-console-auto-research-waiting-points",
                    ("done", project.PathDone), ("total", project.PathTotal)))
            : Loc.GetString("research-console-auto-research-queued",
                ("done", project.PathDone), ("total", project.PathTotal));
        var sub = new Label { Text = $"{status} {subText}", ClipText = true };
        LunaWindowStyle.StyleMuted(sub);
        box.AddChild(sub);
        if (progress && project.Cost > 0)
        {
            var bar = new ProgressBar
            {
                MinValue = 0,
                MaxValue = 1,
                Value = Math.Clamp(project.Progress / (float) Math.Max(1, project.Cost), 0f, 1f),
                MinWidth = 148,
                SetHeight = 5,
                Margin = new Thickness(0, 2, 0, 0),
            };
            LunaWindowStyle.StyleProgressGood(bar, 5f);
            box.AddChild(bar);
        }

        panel.AddChild(box);
        return panel;
    }

    private ResearchProjectUiState? FindProject(string id)
    {
        foreach (var p in _active)
        {
            if (p.Id == id)
            {
                if (p.CurrentStepId == id && p.StepCost > 0)
                    return StepProgressProxy(p);
                return p;
            }

            if (p.CurrentStepId == id && p.StepCost > 0)
                return StepProgressProxy(p);
        }

        foreach (var p in _queued)
        {
            if (p.Id == id)
            {
                if (p.CurrentStepId == id && p.StepCost > 0)
                    return StepProgressProxy(p);
                return p;
            }

            if (p.CurrentStepId == id && p.StepCost > 0)
                return StepProgressProxy(p);
        }

        if (_technologyProgress.TryGetValue(id, out var invested) &&
            invested > 0 &&
            _prototype.TryIndex<TechnologyPrototype>(id, out var proto))
        {
            return new ResearchProjectUiState
            {
                Id = id,
                Name = Loc.GetString(proto.Name),
                Progress = invested,
                Cost = proto.Cost,
                Started = false,
                RemainingSeconds = (int) Math.Ceiling(Math.Max(0, proto.Cost - invested) / 100.0),
                CurrentStepId = id,
                StepProgress = invested,
                StepCost = proto.Cost,
                CanCancel = false,
            };
        }

        return null;
    }

    private static ResearchProjectUiState StepProgressProxy(ResearchProjectUiState focus)
    {
        return new ResearchProjectUiState
        {
            Id = focus.CurrentStepId,
            Name = focus.Name,
            Progress = focus.StepProgress,
            Cost = focus.StepCost,
            Started = focus.Started,
            RemainingSeconds = focus.RemainingSeconds,
            CurrentStepId = focus.CurrentStepId,
            StepProgress = focus.StepProgress,
            StepCost = focus.StepCost,
            PathDone = focus.PathDone,
            PathTotal = focus.PathTotal,
            CanCancel = true,
        };
    }

    private HashSet<string> CollectVisible()
    {
        var allowed = new HashSet<string>();
        foreach (var (id, _) in List)
        {
            if (!_prototype.TryIndex<TechnologyPrototype>(id, out var proto) || proto.Hidden)
                continue;
            if (!_research.IsTechnologyFactionAllowed(_faction, proto))
                continue;
            allowed.Add(id);
        }

        EnsureSector();
        if (_sectorId == null)
            return allowed;

        if (!_prototype.TryIndex<TechnologyPrototype>(_sectorId, out var sectorHub))
            return allowed;

        var visible = new HashSet<string>();
        if (allowed.Contains(_sectorId))
            visible.Add(_sectorId);

        foreach (var id in allowed)
        {
            if (visible.Contains(id))
                continue;
            if (BelongsToSector(id, sectorHub.Discipline))
                visible.Add(id);
        }

        return visible;
    }

    private bool BelongsToSector(string id, ProtoId<TechDisciplinePrototype> hubDiscipline)
    {
        var visited = new HashSet<string>();
        var stack = new Stack<string>();
        stack.Push(id);
        var hitSelected = false;

        while (stack.Count > 0)
        {
            var current = stack.Pop();
            if (!visited.Add(current))
                continue;

            if (current == _sectorId)
            {
                hitSelected = true;
                continue;
            }

            if (!_prototype.TryIndex<TechnologyPrototype>(current, out var proto))
                continue;

            foreach (var prereq in _research.GetTechnologyPrerequisites(_faction, proto))
                stack.Push(prereq);
        }

        if (hitSelected)
            return true;
        return _prototype.TryIndex<TechnologyPrototype>(id, out var tech) && tech.HasDiscipline(hubDiscipline);
    }

