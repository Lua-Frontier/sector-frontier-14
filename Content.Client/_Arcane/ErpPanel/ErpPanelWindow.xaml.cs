    private Button PrepareInteractionButton(PanelInteractionPrototype interaction)
    {
        var interactionName = GetInteractionName(interaction);
        var isExplicit = interaction.Kind == PanelInteractionKind.Erotic;
        var isHostile = interaction.Kind is PanelInteractionKind.Harmful or PanelInteractionKind.HarmfulErotic; // Lua

        var accentColor = isHostile ? HostileAccentColor : (isExplicit ? ExplicitAccentColor : FriendlyAccentColor);
        var hoverStyle = isHostile ? HostileButtonHoverStyle : (isExplicit ? ExplicitButtonHoverStyle : FriendlyButtonHoverStyle);

        // Lua start
        var arrow = new TextureRect
        {
            StyleClasses = { OptionButton.StyleClassOptionTriangle },
            MinWidth = 12,
            VerticalAlignment = VAlignment.Center,
            MouseFilter = MouseFilterMode.Ignore,
        };
        var button = new InteractionButton(hoverStyle, arrow, accentColor)
        {
            HorizontalExpand = true,
            MinWidth = 250,
            MinHeight = 56,
            ToolTip = interactionName,
            StyleClasses = { StyleBase.ButtonSquare },
            ModulateSelfOverride = Color.White, // StyleNano tints ButtonSquare by #232323
        };
        // Lua end

        var content = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(7, 5),
            SeparationOverride = 8,
            MouseFilter = MouseFilterMode.Ignore,
        };
        var accent = new PanelContainer
        {
            MinWidth = 3,
            VerticalExpand = true,
            PanelOverride = isHostile ? HostileAccentStyle : (isExplicit ? ExplicitAccentStyle : FriendlyAccentStyle),
            MouseFilter = MouseFilterMode.Ignore,
        };
        var iconFrame = new PanelContainer
        {
            MinWidth = 40,
            MinHeight = 40,
            PanelOverride = IconStyle, // Lua
            MouseFilter = MouseFilterMode.Ignore,
        };
        var icon = new TextureRect
        {
            Texture = _sprite.Frame0(interaction.Icon),
            MinWidth = 32,
            MinHeight = 32,
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            VerticalAlignment = VAlignment.Center,
            MouseFilter = MouseFilterMode.Ignore,
        };
        var label = new Label
        {
            Text = interactionName,
            FontColorOverride = LunaWindowStyle.TextPrimary, // Lua
            ClipText = true,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
            ToolTip = interactionName,
            MouseFilter = MouseFilterMode.Ignore,
        };
        button.OnPressed += _ =>
        {
            OnSendEmote?.Invoke(interaction.ID, PrivateModeToggle.Pressed); // Lua

            var cooldownEnd = _timing.CurTime + ErpPanelOwnerComponent.Cooldown;
            foreach (var interactionId in _interactionButtons.Keys)
                _cooldownEnds[interactionId] = cooldownEnd;
            UpdateCooldownsImmediately();
        };

        iconFrame.AddChild(icon);
        content.AddChild(accent);
        content.AddChild(iconFrame);
        content.AddChild(label);
        content.AddChild(arrow);
        button.AddChild(content);
        _interactionButtons[interaction.ID] = button;

        return button;
    }

    // Lua: picks the look from DrawMode, so hover survives the cooldown
    private sealed class InteractionButton(StyleBoxFlat hoverStyle, TextureRect arrow, Color accent) : Button
    {
        // field initializers run before the base ctor, which already calls DrawModeChanged
        private readonly StyleBoxFlat _hoverStyle = hoverStyle;
        private readonly TextureRect _arrow = arrow;
        private readonly Color _accent = accent;

        protected override void DrawModeChanged()
        {
            base.DrawModeChanged();
            var hovered = DrawMode is DrawModeEnum.Hover or DrawModeEnum.Pressed;
            StyleBoxOverride = hovered ? _hoverStyle : ButtonStyle;
            _arrow.Modulate = hovered ? Color.White : _accent;
            Modulate = Disabled ? DisabledModulate : Color.White; // dims the whole button, same as disabled sliders
        }
    }

    private void UpdateCatalogSummary(int interactionCount)
    {
        ResultsLabel.Text = Loc.GetString("erp-panel-results", ("count", interactionCount));

        var hasInteractions = interactionCount > 0;
        InteractionScroll.Visible = hasInteractions;
        EmptyStateContainer.Visible = !hasInteractions;
        EmptyStateLabel.Text = Loc.GetString(
            string.IsNullOrWhiteSpace(SearchInput.Text)
                ? "erp-panel-empty-available"
                : "erp-panel-empty-search");

        ExpandAllButton.Disabled = _categoryControls.Count == 0;
        CollapseAllButton.Disabled = _categoryControls.Count == 0;
    }

    private void SetAllCategoriesExpanded(bool expanded)
    {
        foreach (var (categoryId, category) in _categoryControls)
        {
            category.BodyVisible = expanded;

            if (expanded)
                _openedCategories.Add(categoryId);
            else
                _openedCategories.Remove(categoryId);
        }
    }

    private void UpdateCooldownsImmediately()
    {

        _lastCooldownUpdate = _timing.CurTime - CooldownUpdateCooldown;
        UpdateCooldowns();
    }

    private bool InteractionMatchesSearch(PanelInteractionPrototype interaction, string searchText)
    {
        if (string.IsNullOrEmpty(searchText))
            return true;

        if (GetInteractionName(interaction).Contains(searchText, StringComparison.CurrentCultureIgnoreCase))
            return true;

        var category = _prototypeManager.Index<PanelInteractionCategoryPrototype>(interaction.Category.Id);
        return GetCategoryName(category).Contains(searchText, StringComparison.CurrentCultureIgnoreCase);
    }

    private string GetInteractionName(PanelInteractionPrototype interaction)
    {
        if (_interactionNames.TryGetValue(interaction.ID, out var name))
            return name;

        name = Loc.GetString($"erp-panel-interaction-{ToKebabCase(interaction.ID)}-name");
        _interactionNames[interaction.ID] = name;
        return name;
    }

    private string GetCategoryName(PanelInteractionCategoryPrototype category)
    {
        if (_categoryNames.TryGetValue(category.ID, out var name))
            return name;

        name = Loc.GetString($"erp-panel-category-{ToKebabCase(category.ID)}-name");
        _categoryNames[category.ID] = name;
        return name;
    }

    private static string FormatPercent(double value)
    {
        return $"{(int) Math.Round(value)}%";
    }

    // Lua
    private static StyleBoxFlat Underlined(Color background, Color border)
    {
        var box = LunaWindowStyle.Box(background, border);
        box.BorderThickness = new Thickness(0, 0, 0, 1);
        return box;
    }

    private static string ToKebabCase(string value)
    {
        var builder = new System.Text.StringBuilder(value.Length * 2);

        for (var i = 0; i < value.Length; i++)
        {
            var character = value[i];

            if (char.IsUpper(character))
            {
                if (i > 0)
                    builder.Append('-');

                builder.Append(char.ToLowerInvariant(character));
                continue;
            }

            builder.Append(character);
        }

        return builder.ToString();
    }

    private bool CheckRequirements(EntityUid user, EntityUid target, PanelInteractionPrototype interaction)
    {
        if (interaction.IsErotic && !CanUseErp(user, target)) // Lua
            return false;

        if (!IsInRange(user, target, interaction.Range)) // Lua
            return false;

        if (interaction.UserRequirements != null)
        {
            foreach (var requirement in interaction.UserRequirements)
            {
                if (!requirement.IsAvailable(user, _entManager))
                    return false;
            }
        }

        if (interaction.TargetRequirements != null)
        {
            foreach (var requirement in interaction.TargetRequirements)
            {
                if (!requirement.IsAvailable(target, _entManager))
                    return false;
            }
        }

        return true;
    }

    // Lua start: same check as the server, one raycast per distinct range
    private bool IsInRange(EntityUid user, EntityUid target, float range)
    {
        if (_rangeCache.TryGetValue(range, out var inRange))
            return inRange;

        inRange = _interaction.InRangeAndAccessible(user, target, range);
        _rangeCache[range] = inRange;
        return inRange;
    }
    // Lua end

    private bool CanUseErp(EntityUid user, EntityUid target)
    {
        if (!_entManager.TryGetComponent<ErpStatusComponent>(user, out var userStatus) ||
            userStatus.Status == EnumERPStatus.NO)
            return false;

        if (user == target)
            return true;

        return _entManager.TryGetComponent<ErpStatusComponent>(target, out var targetStatus)
               && targetStatus.Status != EnumERPStatus.NO;
    }
