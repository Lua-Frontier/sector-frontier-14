    public void SetMatrix(EntityCoordinates? coordinates, Angle? angle)
    {
        if (_wasPanned) // Mono hack
            return;

        _coordinates = coordinates;
        // Seed rotation once; Draw drives it via _angleFollow afterwards.
        _rotation ??= angle ?? Angle.Zero;
