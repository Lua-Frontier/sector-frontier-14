    private void DrawCoordinateGrid(DrawingHandleScreen handle, Matrix3x2 mapTransform, Box2 viewBox)
    {
        if (MinimapScale <= 0f)
            return;

        var minorStep = GetNiceGridStep(46f / MinimapScale);
        var majorStep = minorStep * 4f;
        var minorColor = Color.FromHex("#7E8BA0").WithAlpha(0.08f);
        var majorColor = Color.FromHex("#8A96A8").WithAlpha(0.16f);
        var axisColor = Color.FromHex("#C5CEDB").WithAlpha(0.28f);
        var labelColor = Color.FromHex("#8A96A8").WithAlpha(0.7f);
        var labelShadow = Color.Black.WithAlpha(0.42f);

        DrawGridAxis(handle, mapTransform, viewBox.Left, viewBox.Right, viewBox.Bottom, viewBox.Top, minorStep, majorStep, minorColor, majorColor, axisColor, vertical: true);
        DrawGridAxis(handle, mapTransform, viewBox.Bottom, viewBox.Top, viewBox.Left, viewBox.Right, minorStep, majorStep, minorColor, majorColor, axisColor, vertical: false);
        DrawCoordinateLabels(handle, mapTransform, viewBox, majorStep, labelColor, labelShadow);
    }

    private static float GetNiceGridStep(float targetWorldStep)
    {
        targetWorldStep = MathF.Max(1f, targetWorldStep);
        var exponent = MathF.Floor(MathF.Log10(targetWorldStep));
        var magnitude = MathF.Pow(10f, exponent);
        var normalized = targetWorldStep / magnitude;
        var nice = normalized <= 1f ? 1f : normalized <= 2f ? 2f : normalized <= 5f ? 5f : 10f;
        return nice * magnitude;
    }

    private void DrawGridAxis(
        DrawingHandleScreen handle,
        Matrix3x2 mapTransform,
        float start,
        float end,
        float crossStart,
        float crossEnd,
        float minorStep,
        float majorStep,
        Color minorColor,
        Color majorColor,
        Color axisColor,
        bool vertical)
    {
        var first = MathF.Floor(start / minorStep) * minorStep;
        for (var value = first; value <= end; value += minorStep)
        {
            var color = MathF.Abs(value) < 0.01f
                ? axisColor
                : IsGridMajor(value, majorStep)
                    ? majorColor
                    : minorColor;

            var a = vertical ? new Vector2(value, crossStart) : new Vector2(crossStart, value);
            var b = vertical ? new Vector2(value, crossEnd) : new Vector2(crossEnd, value);
            LunaDraw.Line(handle, MapToScreen(a, mapTransform), MapToScreen(b, mapTransform), color);
        }
    }

    private void DrawCoordinateLabels(
        DrawingHandleScreen handle,
        Matrix3x2 mapTransform,
        Box2 viewBox,
        float majorStep,
        Color color,
        Color shadow)
    {
        var firstX = MathF.Floor(viewBox.Left / majorStep) * majorStep;
        for (var x = firstX; x <= viewBox.Right; x += majorStep)
        {
            var pos = MapToScreen(new Vector2(x, viewBox.Top), mapTransform) + new Vector2(4f, 5f);
            DrawSoftMapText(handle, x.ToString("0"), pos, 0.72f, color, shadow);
        }

        var firstY = MathF.Floor(viewBox.Bottom / majorStep) * majorStep;
        for (var y = firstY; y <= viewBox.Top; y += majorStep)
        {
            var pos = MapToScreen(new Vector2(viewBox.Left, y), mapTransform) + new Vector2(6f, -10f);
            DrawSoftMapText(handle, y.ToString("0"), pos, 0.72f, color, shadow);
        }
    }

    private static bool IsGridMajor(float value, float majorStep)
        => MathF.Abs(value / majorStep - MathF.Round(value / majorStep)) < 0.02f;

    private Vector2 MapToScreen(Vector2 worldPosition, Matrix3x2 mapTransform)
    {
        var adjusted = Vector2.Transform(worldPosition, mapTransform);
        return ScalePosition(adjusted with { Y = -adjusted.Y });
    }

    private void DrawMapCompass(DrawingHandleScreen handle)
    {
        var center = new Vector2(PixelWidth - 44f, 44f);
        const float radius = 24f;
        var ringColor = Color.FromHex("#8A96A8").WithAlpha(0.2f);
        var northColor = Color.FromHex("#F0C674").WithAlpha(0.86f);
        var eastColor = Color.FromHex("#7E8BA0").WithAlpha(0.82f);
        var headingColor = Color.FromHex("#5EC8E8").WithAlpha(0.9f);

        LunaDraw.Circle(handle, center, radius, ringColor, false);
        LunaDraw.Circle(handle, center, 2.5f, ringColor.WithAlpha(0.8f), true);
        DrawMapCompassNeedle(handle, center, new Vector2(0f, -1f), radius, "N", northColor);
        DrawMapCompassNeedle(handle, center, new Vector2(1f, 0f), radius * 0.82f, "E", eastColor);
        if (_shuttleEntity is { } shuttle && EntManager.EntityExists(shuttle))
        {
            var heading = _xformSystem.GetWorldRotation(shuttle);
            var direction = GetMapCompassDirection(heading);
            DrawMapArrowLine(handle, center - direction * 7f, center + direction * (radius * 0.62f), headingColor, 7f);
        }
    }

    private static Vector2 GetMapCompassDirection(Angle heading)
    {
        var radians = (float) heading.Theta + MathF.PI / 2f;
        return new Vector2(MathF.Cos(radians), -MathF.Sin(radians));
    }

    private void DrawMapCompassNeedle(DrawingHandleScreen handle, Vector2 center, Vector2 direction, float radius, string label, Color color)
    {
        var tip = center + direction * radius;
        var tail = center - direction * (radius * 0.35f);
        DrawMapArrowLine(handle, tail, tip, color.WithAlpha(0.64f), 6f);

        var labelSize = handle.GetDimensions(_font, label, 0.85f);
        var labelPos = tip + direction * 6f - labelSize * 0.5f;
        DrawSoftMapText(handle, label, labelPos, 0.85f, color, Color.Black.WithAlpha(0.46f));
    }

    private static void DrawMapArrowLine(DrawingHandleScreen handle, Vector2 start, Vector2 end, Color color, float headLength)
    {
        var direction = end - start;
        if (direction.LengthSquared() <= 0.001f)
            return;

        direction = Vector2.Normalize(direction);
        var side = new Vector2(-direction.Y, direction.X);
        LunaDraw.Line(handle, start, end, color);
        LunaDraw.Line(handle, end, end - direction * headLength + side * (headLength * 0.45f), color);
        LunaDraw.Line(handle, end, end - direction * headLength - side * (headLength * 0.45f), color);
    }

    private void DrawSoftMapText(DrawingHandleScreen handle, string text, Vector2 position, float scale, Color color, Color shadow)
    {
        handle.DrawString(_font, position + new Vector2(1f, 1f), text, scale, shadow);
        handle.DrawString(_font, position, text, scale, color);
    }

    private Box2 GetVisibleWorldBox()
    {
        var scale = MinimapScale;
        if (scale <= 0f)
            return Box2.CenteredAround(Offset, WorldRangeVector * 2f);

        var mid = MidPointVector;
        var minLocal = -mid;
        var maxLocal = new Vector2(PixelWidth, PixelHeight) - mid;
        var worldMinX = Offset.X + minLocal.X / scale;
        var worldMaxX = Offset.X + maxLocal.X / scale;
        var yA = Offset.Y - minLocal.Y / scale;
        var yB = Offset.Y - maxLocal.Y / scale;
        return new Box2(
            MathF.Min(worldMinX, worldMaxX),
            MathF.Min(yA, yB),
            MathF.Max(worldMinX, worldMaxX),
            MathF.Max(yA, yB));
    }

    /// <summary>
    /// Gets the map objects that intersect the viewport.
    /// </summary>
    /// <param name="mapObjects"></param>
    /// <returns></returns>
    private List<IMapObject> GetViewportMapObjects(Matrix3x2 matty, List<IMapObject> mapObjects)
    {
        var results = new List<IMapObject>();
        var enlargement = new Vector2i((int) (16 * UIScale), (int) (16 * UIScale));
        var viewBox = new UIBox2i(Vector2i.Zero - enlargement, PixelSize + enlargement);

        foreach (var mapObj in mapObjects)
        {
            // If it's a grid-map skip it.
            if (mapObj is GridMapObject gridObj && (EntManager.HasComponent<MapComponent>(gridObj.Entity) || !_entManager.EntityExists(gridObj.Entity))) // Frontier: add EntityExists
                continue;

            if (mapObj is GridMapObject veiledGrid &&
                veiledGrid.Entity != _shuttleEntity &&
                IsHiddenByNebulaVeil(veiledGrid.Entity))
                continue;

            var mapCoords = _shuttles.GetMapCoordinates(mapObj);

            var relativePos = Vector2.Transform(mapCoords.Position, matty);
            relativePos = relativePos with { Y = -relativePos.Y };
            var uiPosition = ScalePosition(relativePos);

            if (!viewBox.Contains(uiPosition.Floored()))
                continue;

            results.Add(mapObj);
        }

        return results;
    }

    private bool IsHiddenByNebulaVeil(EntityUid gridUid)
    {
        if (!EntManager.TryGetComponent(gridUid, out NebulaPresenceComponent? presence))
            return false;

        var prototypes = IoCManager.Resolve<IPrototypeManager>();
        if (presence.ActiveWeathers.Count == 0)
            return prototypes.TryIndex(presence.Weather, out NebulaWeatherPrototype? fallback) &&
                   fallback.Kind == NebulaWeatherKind.Veil;

        foreach (var weatherId in presence.ActiveWeathers)
        {
            if (prototypes.TryIndex(weatherId, out NebulaWeatherPrototype? weather) &&
                weather.Kind == NebulaWeatherKind.Veil)
                return true;
        }

        return false;
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);

        if (ViewingMap == MapId.Nullspace)
            return;

        var mapObjects = _mapObjects;
        DrawRecenter();

        if (InFtl || mapObjects.Count == 0)
        {
            DrawBacking(handle);
            DrawNoSignal(handle);
            return;
        }

        var viewedMapUid = _mapSystem.GetMapOrInvalid(ViewingMap);
        var matty = Matrix3Helpers.CreateInverseTransform(Offset, Angle.Zero);
        var realTime = _timing.RealTime;
        var viewBox = GetVisibleWorldBox();
        DrawTacticalMapBackground(handle, matty, viewBox);
        var viewportObjects = GetViewportMapObjects(matty, mapObjects);
        _viewportExclusions.Clear();

        // Draw our FTL range + no FTL zones
        // Do it up here because we want this layered below most things.
        if ((FtlMode || ShowFTLRangeOnly) && ShowFTLRange)
        {
            if (EntManager.TryGetComponent<TransformComponent>(_shuttleEntity, out var shuttleXform))
            {
                var gridUid = _shuttleEntity.Value;
                var gridPhysics = _physicsQuery.GetComponent(gridUid);
                var (gridPos, gridRot) = _xformSystem.GetWorldPositionRotation(shuttleXform);
                gridPos = Maps.GetGridPosition((gridUid, gridPhysics), gridPos, gridRot);

                var gridRelativePos = Vector2.Transform(gridPos, matty);
                gridRelativePos = gridRelativePos with { Y = -gridRelativePos.Y };
                var gridUiPos = ScalePosition(gridRelativePos);

                var range = _shuttles.GetFTLRange(gridUid);
                range *= MinimapScale;
                LunaDraw.Circle(handle, gridUiPos, range, Color.Gold, filled: false);
            }
        }

        var exclusionColor = Color.Red;

        // Exclusions need a bumped range so we check all the ones on the map.
        foreach (var mapObj in mapObjects)
        {
            if (mapObj is not ShuttleExclusionObject exclusion)
                continue;

            // Check if it even intersects the viewport.
            var coords = EntManager.GetCoordinates(exclusion.Coordinates);
            var mapCoords = _xformSystem.ToMapCoordinates(coords);
            var enlargedBounds = viewBox.Enlarged(exclusion.Range);

            if (mapCoords.MapId != ViewingMap ||
                !enlargedBounds.Contains(mapCoords.Position))
            {
                continue;
            }
            _viewportExclusions.Add(exclusion);

            if (!exclusion.Visible)
                continue;

            var adjustedPos = Vector2.Transform(mapCoords.Position, matty);
            var localPos = ScalePosition(adjustedPos with { Y = -adjustedPos.Y});
            LunaDraw.Circle(handle, localPos, exclusion.Range * MinimapScale, exclusionColor.WithAlpha(0.05f));
            LunaDraw.Circle(handle, localPos, exclusion.Range * MinimapScale, exclusionColor, filled: false);
        }
        DrawMapSpaceHazards(handle, matty, viewBox);

        _verts.Clear();
        _edges.Clear();
        _strings.Clear();
        _glyphs.Clear();

        // Add beacons if relevant.
        var beaconsOnly = _shuttles.IsBeaconMap(viewedMapUid);
        var controlLocalBounds = PixelRect;
        _beacons.Clear();

        if (ShowBeacons)
        {
            var beaconColor = Color.AliceBlue;

            foreach (var (beaconName, coords, mapO) in GetBeacons(viewportObjects, matty, controlLocalBounds))
            {
                var localPos = Vector2.Transform(coords.Position, matty);
                localPos = localPos with { Y = -localPos.Y };
                var beaconUiPos = ScalePosition(localPos);
                var mapObject = GetMapObject(localPos, Angle.Zero, scale: 0.75f, scalePosition: true);

                // Get company color if the beacon has it
                var displayColor = beaconColor;
                if (mapO is GridMapObject gridObj &&
                    EntManager.TryGetComponent(gridObj.Entity, out Shared._Mono.Company.CompanyComponent? companyComp) &&
                    !string.IsNullOrEmpty(companyComp.CompanyName) &&
                    IoCManager.Resolve<IPrototypeManager>().TryIndex<CompanyPrototype>(companyComp.CompanyName, out var beaconCompanyProto))
                {
                    displayColor = Color.FromSrgb(beaconCompanyProto.Color);
                }

                var existingVerts = _verts.GetOrNew(displayColor);
                var existingEdges = _edges.GetOrNew(displayColor);

                AddMapObject(existingEdges, existingVerts, mapObject);
                _beacons.Add(mapO);
                _glyphs.Add((beaconUiPos, "◎", displayColor));
            }
        }

        // Lua start
        Vector2 viewerPos = default;
        var haveViewerPos = false;
        if (_shuttleEntity != null && EntManager.EntityExists(_shuttleEntity.Value) && EntManager.TryGetComponent<MapGridComponent>(_shuttleEntity.Value, out var viewerGridComp))
        {
            var viewerPhysics = _physicsQuery.GetComponent(_shuttleEntity.Value);
            var (vp, vr) = _xformSystem.GetWorldPositionRotation(_shuttleEntity.Value);
            Entity<MapGridComponent> viewerGrid = (_shuttleEntity.Value, viewerGridComp);
            viewerPos = Maps.GetGridPosition((viewerGrid, viewerPhysics), vp, vr);
            haveViewerPos = true;
        }
        var viewerCompanyName = string.Empty;
        if (_shuttleEntity != null && EntManager.TryGetComponent(_shuttleEntity.Value, out CompanyComponent? viewerCompany))
        { viewerCompanyName = viewerCompany.CompanyName; }
        // Lua end

        foreach (var mapObj in viewportObjects)
        {
            if (mapObj is not GridMapObject gridObj || !EntManager.TryGetComponent(gridObj.Entity, out MapGridComponent? mapGrid))
                continue;

            Entity<MapGridComponent> grid = (gridObj.Entity, mapGrid);
            EntManager.TryGetComponent(grid, out IFFComponent? iffComp);
            if (grid.Owner != _shuttleEntity && !_shuttles.CanDraw(grid.Owner, iffComp: iffComp))
                continue;

            var gridColor = _shuttles.GetIFFColor(grid, self: _shuttleEntity == grid.Owner, component: iffComp);
            if (EntManager.TryGetComponent(grid.Owner, out CompanyComponent? mapGridCompany)
                && !string.IsNullOrEmpty(mapGridCompany.CompanyName)
                && !string.Equals(mapGridCompany.CompanyName, "None", StringComparison.OrdinalIgnoreCase)
                && IoCManager.Resolve<IPrototypeManager>().TryIndex<CompanyPrototype>(mapGridCompany.CompanyName, out var mapGridCompanyProto))
            {
                gridColor = mapGridCompanyProto.Color;
            }

            var existingVerts = _verts.GetOrNew(gridColor);
            var existingEdges = _edges.GetOrNew(gridColor);

            var gridPhysics = _physicsQuery.GetComponent(grid.Owner);
            var (gridPos, gridRot) = _xformSystem.GetWorldPositionRotation(grid.Owner);
            gridPos = Maps.GetGridPosition((grid, gridPhysics), gridPos, gridRot);

            var gridRelativePos = Vector2.Transform(gridPos, matty);
            gridRelativePos = gridRelativePos with { Y = -gridRelativePos.Y };
            var gridUiPos = ScalePosition(gridRelativePos);

            // Lua decrypt mod start
            var flags = iffComp?.Flags ?? IFFFlags.None;
            var hideLabel = (flags & IFFFlags.HideLabel) != 0x0;
            var hideLabelShuttle = (flags & IFFFlags.HideLabelShuttle) != 0x0;
            var allyByCompany = false;
            if (hideLabelShuttle && EntManager.TryGetComponent(grid.Owner, out CompanyComponent? targetCompany) && !string.IsNullOrEmpty(targetCompany.CompanyName) && !string.IsNullOrEmpty(viewerCompanyName) && viewerCompanyName == targetCompany.CompanyName && IoCManager.Resolve<IPrototypeManager>().TryIndex<CompanyPrototype>(targetCompany.CompanyName, out var targetProto) && targetProto.AliesOnRadar)
            { allyByCompany = true; }
            var effectiveHideLabelShuttle = hideLabelShuttle && !allyByCompany;
            if (!hideLabelShuttle && hideLabel)
            {
                var mapObject = GetMapObject(gridRelativePos, Angle.Zero, scalePosition: true);
                AddMapObject(existingEdges, existingVerts, mapObject);
                continue;
            }
            // Lua decrypt mod end

            var iffText = _shuttles.GetIFFLabel(grid, self: _shuttleEntity == grid.Owner, component: iffComp); // Lua decrypt mod
            if (iffText == null)
            {
                // Lua decrypt mod start
                if (haveViewerPos && _shuttleEntity != null)
                {
                    var realName = EntManager.TryGetComponent<MetaDataComponent>(grid.Owner, out var meta) ? meta.EntityName : string.Empty;
                    var dist = Vector2.Distance(viewerPos, gridPos);
                    if (effectiveHideLabelShuttle)
                    {
                        var decrypt = _iffDecrypt.Get(_shuttleEntity.Value, grid.Owner, realName, dist, hideLabel: true);
                        if (decrypt.Phase != IFFDecryptPhase.Known) continue;
                        iffText = decrypt.Revealed;
                    }
                    else if (hideLabelShuttle && allyByCompany)
                    { iffText = realName; } else { iffText = Loc.GetString("shuttle-console-unknown"); }
                }
                else { iffText = Loc.GetString("shuttle-console-unknown"); }
                // Lua decrypt mod end
            }

            if (string.IsNullOrEmpty(iffText))
                continue;

            var mapObj2 = GetMapObject(gridRelativePos, Angle.Zero, scalePosition: true); // Lua decrypt mod
            AddMapObject(existingEdges, existingVerts, mapObj2); // Lua decrypt mod
            var existingStrings = _strings.GetOrNew(gridColor);
            existingStrings.Add((gridUiPos, iffText));
        }

        // Batch the colors whoopie
        // really only affects forks with lots of grids.
        foreach (var (color, sendVerts) in _verts)
        {
            handle.DrawPrimitives(DrawPrimitiveTopology.TriangleList, sendVerts, color.WithAlpha(0.05f));
        }

        foreach (var (color, sendEdges) in _edges)
        {
            var edgeColor = color.WithAlpha(0.78f);
            for (var i = 0; i + 1 < sendEdges.Count; i += 2)
                LunaDraw.Line(handle, sendEdges[i], sendEdges[i + 1], edgeColor);
        }

        foreach (var (position, icon, color) in _glyphs)
        {
            var size = handle.GetDimensions(_font, icon, 0.92f);
            DrawSoftMapText(handle, icon, position - size * 0.5f, 0.92f, color.WithAlpha(0.96f), Color.Black.WithAlpha(0.55f));
        }

        foreach (var (color, sendStrings) in _strings)
        {
            var displayColor = Color.FromSrgb(color);

            foreach (var (gridUiPos, iffText) in sendStrings)
            {
                var lines = iffText.Split('\n');
                var mainLabel = lines[0];
                var mainTextWidth = handle.GetDimensions(_font, mainLabel, 1f);

                DrawSoftMapText(handle, mainLabel, gridUiPos + mainTextWidth with { X = -mainTextWidth.X / 2f, Y = mainTextWidth.Y * UIScale }, 1f, displayColor.WithAlpha(0.92f), Color.Black.WithAlpha(0.48f));

                if (lines.Length > 1)
                {
                    var companyLabel = lines[1];
                    var companyTextWidth = handle.GetDimensions(_font, companyLabel, 1f);
                    var companyLabelOffset = mainTextWidth with
                    {
                        X = -companyTextWidth.X / 2f,
                        Y = mainTextWidth.Y * 2 * UIScale
                    };

                    DrawSoftMapText(handle, companyLabel, gridUiPos + companyLabelOffset, 1f, displayColor.WithAlpha(0.78f), Color.Black.WithAlpha(0.42f));
                }
            }
        }

        var mousePos = _inputs.MouseScreenPosition;
        var mouseLocalPos = GetLocalPosition(mousePos);

        DrawDroneRoutes(handle, matty, (float) realTime.TotalSeconds * 30f);

        // Draw dotted line from our own shuttle entity to mouse.
        if (FtlMode && !ShowFTLRangeOnly)
        {
            if (mousePos.Window != WindowId.Invalid)
            {
                // If mouse inbounds then draw it.
                if (_shuttleEntity != null && controlLocalBounds.Contains(mouseLocalPos.Floored()) &&
                    EntManager.TryGetComponent(_shuttleEntity, out TransformComponent? shuttleXform) &&
                    shuttleXform.MapID != MapId.Nullspace)
                {
                    // If it's a beacon only map then snap the mouse to a nearby spot.
                    ShuttleBeaconObject foundBeacon = default;

                    // Check for beacons around mouse and snap to that.
                    if (beaconsOnly && TryGetBeacon(viewportObjects, matty, mouseLocalPos, controlLocalBounds, out foundBeacon, out var foundLocalPos))
                    {
                        mouseLocalPos = foundLocalPos;
                    }

                    var grid = EntManager.GetComponent<MapGridComponent>(_shuttleEntity.Value);

                    var (gridPos, gridRot) = _xformSystem.GetWorldPositionRotation(shuttleXform);
                    gridPos = Maps.GetGridPosition(_shuttleEntity.Value, gridPos, gridRot);

                    // do NOT apply LocalCenter operation here because it will be adjusted in FTLFree.
                    var mouseMapPos = InverseMapPosition(mouseLocalPos);

                    var ftlFree = (!beaconsOnly || foundBeacon != default) &&
                                  _shuttles.FTLFree(_shuttleEntity.Value, new EntityCoordinates(viewedMapUid, mouseMapPos), _ftlAngle, _viewportExclusions)
                                  || NoFTLRange; // Mono

                    var color = ftlFree ? Color.LimeGreen : Color.Magenta;

                    var gridRelativePos = Vector2.Transform(gridPos, matty);
                    gridRelativePos = gridRelativePos with { Y = -gridRelativePos.Y };
                    var gridUiPos = ScalePosition(gridRelativePos);

                    // Draw FTL buffer around the mouse.
                    var ourFTLBuffer = _shuttles.GetFTLBufferRange(_shuttleEntity.Value, grid);
                    ourFTLBuffer *= MinimapScale;
                    LunaDraw.Circle(handle, mouseLocalPos, ourFTLBuffer, Color.Magenta.WithAlpha(0.01f));
                    LunaDraw.Circle(handle, mouseLocalPos, ourFTLBuffer, Color.Magenta, filled: false);

                    // Draw line from our shuttle to target
                    // Might need to clip the line if it's too far? But my brain wasn't working so F.
                    LunaDraw.DashedLine(handle, gridUiPos, mouseLocalPos, color, dashLength: 8f, gapLength: 2f, offset: (float) realTime.TotalSeconds * 30f);

                    // Draw shuttle pre-vis
                    var mouseVerts = GetMapObject(mouseLocalPos, -_ftlAngle, scale: MinimapScale); // Mono Edit: UI controls and the map are in different coordinate orientations, so the angle has to be negated. (shuttle Y is UI control -Y)

                    handle.DrawPrimitives(DrawPrimitiveTopology.TriangleFan, mouseVerts.Span, color.WithAlpha(0.05f));
                    DrawMapObjectOutline(handle, mouseVerts, color);

                    // Draw a notch indicating direction.
                    var ftlLength = GetMapObjectRadius() + 16f;
                    var ftlEnd = mouseLocalPos + (-_ftlAngle).RotateVec(new Vector2(0f, -ftlLength)); // Mono Edit: UI controls and the map are in different coordinate orientations, so the angle has to be negated. (shuttle Y is UI control -Y)

                    LunaDraw.Line(handle, mouseLocalPos, ftlEnd, color);
                }
            }
        }

        // Draw the coordinates
        var mapOffset = MidPointVector;

        if (mousePos.Window != WindowId.Invalid &&
            controlLocalBounds.Contains(mouseLocalPos.Floored()))
        {
            mapOffset = mouseLocalPos;
        }

        mapOffset = InverseMapPosition(mapOffset);
        var coordsText = $"{mapOffset.X:0.0}, {mapOffset.Y:0.0}";

        // Get company color if available
        var coordColor = Color.White;
        if (_shuttleEntity != null &&
            EntManager.TryGetComponent(_shuttleEntity.Value, out Shared._Mono.Company.CompanyComponent? shipCompanyComp) &&
            !string.IsNullOrEmpty(shipCompanyComp.CompanyName) &&
            IoCManager.Resolve<IPrototypeManager>().TryIndex<CompanyPrototype>(shipCompanyComp.CompanyName, out var shipCompanyProto))
        {
            coordColor = shipCompanyProto.Color;
        }

        DrawMapData(handle, coordsText, coordColor);
    }

    private void AddMapObject(List<Vector2> edges, List<Vector2> verts, ValueList<Vector2> mapObject)
    {
        var bottom = mapObject[0];
        var right = mapObject[1];
        var top = mapObject[2];
        var left = mapObject[3];

        // Diamond interior
        verts.Add(bottom);
        verts.Add(right);
        verts.Add(top);

        verts.Add(bottom);
        verts.Add(top);
        verts.Add(left);

        // Diamond edges
        edges.Add(bottom);
        edges.Add(right);
        edges.Add(right);
        edges.Add(top);
        edges.Add(top);
        edges.Add(left);
        edges.Add(left);
        edges.Add(bottom);
    }

    private static void DrawMapObjectOutline(DrawingHandleScreen handle, ValueList<Vector2> mapObject, Color color)
    {
        var count = mapObject.Count;
        if (count < 2)
            return;

        for (var i = 0; i < count; i++)
            LunaDraw.Line(handle, mapObject[i], mapObject[(i + 1) % count], color);
    }

    /// <summary>
    /// Returns the beacons that intersect the viewport.
    /// </summary>
    private IEnumerable<(string Beacon, MapCoordinates Coordinates, IMapObject MapObject)> GetBeacons(List<IMapObject> mapObjs, Matrix3x2 mapTransform, UIBox2i area)
    {
        foreach (var mapO in mapObjs)
        {
            if (mapO is not ShuttleBeaconObject beacon)
                continue;

            var beaconCoords = _xformSystem.ToMapCoordinates(EntManager.GetCoordinates(beacon.Coordinates));
            var position = Vector2.Transform(beaconCoords.Position, mapTransform);
            var localPos = ScalePosition(position with {Y = -position.Y});

            // If beacon not on screen then ignore it.
            if (!area.Contains(localPos.Floored()))
                continue;

            yield return (beacon.Name, beaconCoords, mapO);
        }
    }

    private float GetMapObjectRadius(float scale = 1f) => WorldRange / 40f * scale;

    private ValueList<Vector2> GetMapObject(Vector2 localPos, Angle angle, float scale = 1f, bool scalePosition = false)
    {
        // Constant size diamonds
        var diamondRadius = GetMapObjectRadius();

        var mapObj = new ValueList<Vector2>(4)
        {
            localPos + angle.RotateVec(new Vector2(0f, -2f * diamondRadius)) * scale,
            localPos + angle.RotateVec(new Vector2(diamondRadius, 0f)) * scale,
            localPos + angle.RotateVec(new Vector2(0f, 2f * diamondRadius)) * scale,
            localPos + angle.RotateVec(new Vector2(-diamondRadius, 0f)) * scale,
        };

        if (scalePosition)
        {
            for (var i = 0; i < mapObj.Count; i++)
            {
                mapObj[i] = ScalePosition(mapObj[i]);
            }
        }

        return mapObj;
    }

    private bool TryGetBeacon(IEnumerable<IMapObject> mapObjects, Matrix3x2 mapTransform, Vector2 mousePos, UIBox2i area, out ShuttleBeaconObject foundBeacon, out Vector2 foundLocalPos)
    {
        // In pixels
        const float BeaconSnapRange = 32f;
        float nearestValue = float.MaxValue;
        foundLocalPos = Vector2.Zero;
        foundBeacon = default;

        foreach (var mapObj in mapObjects)
        {
            if (mapObj is not ShuttleBeaconObject beaconObj)
                continue;

            var beaconCoords = _xformSystem.ToMapCoordinates(EntManager.GetCoordinates(beaconObj.Coordinates));

            if (beaconCoords.MapId != ViewingMap)
                continue;

            // Invalid beacon?
            if (!_shuttles.CanFTLBeacon(beaconObj.Coordinates))
                continue;

            var position = Vector2.Transform(beaconCoords.Position, mapTransform);
            var localPos = ScalePosition(position with {Y = -position.Y});

            // If beacon not on screen then ignore it.
            if (!area.Contains(localPos.Floored()))
                continue;

            var distance = (localPos - mousePos).Length();

            if (distance > BeaconSnapRange * UIScale ||
                distance > nearestValue)
            {
                continue;
            }

            foundLocalPos = localPos;
            nearestValue = distance;
            foundBeacon = beaconObj;
        }

        return foundBeacon != default;
    }

    /// <summary>
    /// Sets the map objects for the next draw.
    /// </summary>
    public void SetMapObjects(Dictionary<MapId, List<IMapObject>> mapObjects)
    {
        _mapObjects.Clear();

        if (mapObjects.TryGetValue(ViewingMap, out var obbies))
        {
            _mapObjects.AddRange(obbies);
        }
    }

    /// <summary>
    /// Draw the coordinate data with a custom color.
    /// </summary>
    private void DrawMapData(DrawingHandleScreen handle, string text, Color color)
    {
        var font = _font;
        var dimensions = handle.GetDimensions(font, text, 1f);
        var position = new Vector2(15f, Height - dimensions.Y - 15f);
        DrawSoftMapText(handle, text, position, 1f, color.WithAlpha(0.9f), Color.Black.WithAlpha(0.5f));
    }
