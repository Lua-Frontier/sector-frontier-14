    /// <summary>
    /// Adds a map object to the specified sector map.
    /// </summary>
    private void AddMapObject(MapId mapId, IMapObject mapObj)
    {
        var existing = _mapObjects.GetOrNew(mapId);
        existing.Add(mapObj);

        var gridContents = _mapHeadings[mapId];

        var gridButton = new Button()
        {
            Text = mapObj.Name,
            HorizontalExpand = true,
            MinHeight = 18f,
        };
        gridButton.AddStyleClass("ButtonSquare");
        gridButton.AddStyleClass(StyleNano.StyleClassButtonNavCompact);

        gridButton.Label.ClipText = true; // Frontier
        gridButton.Label.FontColorOverride = Color.FromHex("#C5CEDB");
        gridButton.Label.FontOverride = _mapObjectFont;

        var iconControl = CreateMapObjectIcon(mapObj);

        var iconSlot = new CenterContainer()
        {
            MinWidth = 16f,
            MaxWidth = 16f,
            MinHeight = 18f,
            VerticalAlignment = VAlignment.Center,
            HorizontalAlignment = HAlignment.Center,
            Children =
            {
                iconControl
            }
        };

        var gridContainer = new BoxContainer()
        {
            SeparationOverride = 4,
            Children =
            {
                iconSlot,
                gridButton
            }
        };

        _mapObjectControls.Add(gridContainer, GetMapObjectSortKey(mapObj));
        gridContents.AddChild(gridContainer);

        gridButton.OnPressed += args =>
        {
            OnMapObjectPress(mapObj);
        };

        // Frontier: tracking button handler
        if (mapObj is GridMapObject gridObj)
        {
            var trackButton = new Button()
            {
                ToolTip = Loc.GetString("shuttle-console-map-track"),
                MinWidth = 32,
                MaxWidth = 32,
                MinHeight = 18f,
            };
            trackButton.AddStyleClass("ButtonSquare");
            trackButton.AddStyleClass(StyleNano.StyleClassButtonNavCompact);
            trackButton.AddChild(new MapTargetIconControl());
            trackButton.OnPressed += args =>
            {
                OnMapObjectTrackPress(mapObj);
            };
            gridContainer.Children.Add(trackButton);
        }
        // End Frontier: tracking button handler

        if (gridContents.ChildCount > 1)
        {
            // Re-sort the children
            _sortChildren.Clear();

            foreach (var child in gridContents.Children)
            {
                DebugTools.Assert(_mapObjectControls.ContainsKey(child));
                _sortChildren.Add(child);
            }

            foreach (var child in _sortChildren)
            {
                child.Orphan();
            }

            _sortChildren.Sort((x, y) =>
            {
                var xKey = _mapObjectControls[x];
                var yKey = _mapObjectControls[y];

                return CompareMapObjectSortKeys(xKey, yKey);
            });

            foreach (var control in _sortChildren)
            {
                gridContents.AddChild(control);
            }
        }
    }

    private MapObjectSortKey GetMapObjectSortKey(IMapObject mapObj)
    {
        var group = mapObj switch
        {
            GridMapObject grid when grid.Entity == _shuttleEntity => 0,
            GridMapObject grid when IsStationMapObject(grid) => 1,
            GridMapObject grid when _entManager.HasComponent<ShuttleDeedComponent>(grid.Entity) => 2,
            GridMapObject => 3,
            ShuttleBeaconObject => 5,
            ShuttleExclusionObject => 6,
            _ => 7,
        };

        return new MapObjectSortKey(group, mapObj.Name);
    }

    private static int CompareMapObjectSortKeys(MapObjectSortKey x, MapObjectSortKey y)
    {
        var groupCompare = x.Group.CompareTo(y.Group);
        if (groupCompare != 0)
            return groupCompare;

        return string.Compare(x.Name, y.Name, StringComparison.CurrentCultureIgnoreCase);
    }

    private Control CreateMapObjectIcon(IMapObject mapObj)
    {
        if (KnownMapObjectNames.IsKnownTradingPoi(mapObj.Name))
            return new MapObjectIconControl(MapObjectIconShape.Pentagon, Color.FromHex("#7DDBA3"), false);
        if (mapObj is ShuttleBeaconObject)
            return new MapObjectIconControl(MapObjectIconShape.Diamond, Color.FromHex("#7DDBA3"), false);
        if (mapObj is ShuttleExclusionObject)
            return new MapObjectIconControl(MapObjectIconShape.Diamond, Color.FromHex("#E07070"), false);
        if (mapObj is GridMapObject grid)
        {
            if (IsStationMapObject(grid))
                return new MapObjectIconControl(MapObjectIconShape.Hexagon, Color.FromHex("#5EC8E8"), true);

            return new MapObjectIconControl(MapObjectIconShape.Triangle, Color.FromHex("#F0C674"), true);
        }

        return new MapObjectIconControl(MapObjectIconShape.Hexagon, Color.FromHex("#8A96A8"), false);
    }

    private static bool IsStationMapObject(GridMapObject grid)
    {
        return KnownMapObjectNames.IsKnownStationOrPoi(grid.Name);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var curTime = _timing.CurTime;
        if (Visible && _shuttleEntity != null
            && _entManager.TryGetComponent(_shuttleEntity, out TransformComponent? shuttleXform)
            && shuttleXform.MapID != MapId.Nullspace
            && MapRadar.ViewingMap != shuttleXform.MapID)
        {
            var targetOffset = _maps.GetGridPosition((_shuttleEntity.Value, null, shuttleXform));
            MapRadar.SetMap(shuttleXform.MapID, targetOffset, recentering: true);
        }

        if (!IsFTLBlocked() && _nextAutoRefresh <= curTime) // Lua
        {
            RebuildMapObjects(); // Lua
            _nextAutoRefresh = curTime + _autoRefreshInterval; // Lua
        }

        var progress = _ftlTime.ProgressAt(curTime);
        FTLBar.SetProgress(float.IsFinite(progress) ? progress : 1);
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        MapRadar.SetMapObjects(_mapObjects);
        base.Draw(handle);
    }

    public void Startup()
    {
        if (_entManager.TryGetComponent(_shuttleEntity, out TransformComponent? shuttleXform))
        {
            SetMap(shuttleXform.MapID, _maps.GetGridPosition((_shuttleEntity.Value, null, shuttleXform)));
        }
    }

