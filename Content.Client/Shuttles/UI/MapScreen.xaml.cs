    /// <summary>
    /// Gets all map objects at time of ping and adds them to pending to be added over time.
    /// </summary>
    private void RebuildMapObjects()
    {
        ClearMapObjects();

        if (_shuttleEntity == null)
            return;

        var mapComps = _entManager.AllEntityQueryEnumerator<MapComponent, TransformComponent, MetaDataComponent>();
        MapId ourMap = MapId.Nullspace;

        if (_entManager.TryGetComponent(_shuttleEntity, out TransformComponent? shuttleXform))
        {
            ourMap = shuttleXform.MapID;
        }

        while (mapComps.MoveNext(out var mapUid, out var mapComp, out var mapXform, out var mapMetadata))
        {
            if (mapComp.MapId != ourMap) continue; // Lua StarMap
            if (_console != null && !_shuttles.CanFTLTo(_shuttleEntity.Value, mapComp.MapId, _console.Value))
            { continue; }
            var mapName = mapMetadata.EntityName;

            if (string.IsNullOrEmpty(mapName))
            {
                mapName = Loc.GetString("shuttle-console-unknown");
            }

            var heading = new CollapsibleHeading(mapName);

            heading.MinHeight = 28f;
            heading.AddStyleClass(ContainerButton.StyleClassButton);
            heading.HorizontalAlignment = HAlignment.Stretch;
            heading.Label.HorizontalAlignment = HAlignment.Center;
            heading.Label.HorizontalExpand = true;
            heading.Label.FontColorOverride = Color.FromHex("#C5CEDB");
            heading.Label.FontOverride = _mapObjectFont;
            heading.Label.AddStyleClass(StyleNano.StyleClassLabelSmall);
            heading.HorizontalExpand = true;

            var gridContents = new BoxContainer()
            {
                Orientation = LayoutOrientation.Vertical,
                VerticalExpand = true,
                SeparationOverride = 3,
            };

            var body = new CollapsibleBody()
            {
                HorizontalAlignment = HAlignment.Stretch,
                VerticalAlignment = VAlignment.Top,
                HorizontalExpand = true,
                Children =
                {
                    gridContents
                }
            };

            var mapButton = new Collapsible(heading, body);

            heading.OnToggled += args =>
            {
                if (args.Pressed)
                {
                    HideOtherCollapsibles(mapButton);
                }
            };

            _mapHeadings.Add(mapComp.MapId, gridContents);
            var viewerCompanyName = string.Empty;
            if (_entManager.TryGetComponent(_shuttleEntity.Value, out CompanyComponent? viewerCompany)) viewerCompanyName = viewerCompany.CompanyName;
            foreach (var grid in _mapManager.GetAllGrids(mapComp.MapId))
            {
                if (grid.Owner != _shuttleEntity && IsHiddenByNebulaVeil(grid.Owner))
                    continue;

                _entManager.TryGetComponent(grid.Owner, out IFFComponent? iffComp);

                // Frontier: Service flags for shuttles
                // If it is a GridMapObject, Turn the mapObj.ServiceFlags into a string like Food = F, Medical = M, etc.
                // This should turn the ServiceFlags into a string like "FM" for Food and Medical.
                var serviceFlagsText = string.Empty;
                if (iffComp?.ServiceFlags != null)
                {
                    serviceFlagsText = _shuttles.GetServiceFlagsSuffix(iffComp.ServiceFlags);
                }

                var flags = iffComp?.Flags ?? IFFFlags.None; // Lua decrypt mod
                var hideLabelShuttle = (flags & IFFFlags.HideLabelShuttle) != 0x0;
                if (hideLabelShuttle && _entManager.TryGetComponent(grid.Owner, out CompanyComponent? gridCompany) && !string.IsNullOrEmpty(gridCompany.CompanyName) && !string.IsNullOrEmpty(viewerCompanyName) && viewerCompanyName == gridCompany.CompanyName && IoCManager.Resolve<IPrototypeManager>().TryIndex<CompanyPrototype>(gridCompany.CompanyName, out var gridCompanyProto) && gridCompanyProto.AliesOnRadar)
                { hideLabelShuttle = false; }
                var gridObj = new GridMapObject()
                {
                    Name = _entManager.GetComponent<MetaDataComponent>(grid.Owner).EntityName + serviceFlagsText,
                    // Frontier: Service Flags
                    ServiceFlags = iffComp?.ServiceFlags ?? ServiceFlags.None,
                    Entity = grid.Owner,
                    HideButton = (flags & IFFFlags.HideLabel) != 0x0 || hideLabelShuttle, // Lua decrypt mod + Lua alliesOnRadar
                };

                // Always show our shuttle immediately
                if (grid.Owner == _shuttleEntity)
                {
                    AddMapObject(mapComp.MapId, gridObj);
                }

                // If we can show it then add it to pending.
                else if (
                    !_shuttles.IsBeaconMap(mapUid) &&
                    _shuttles.CanDraw(grid.Owner, iffComp: iffComp) &&
                    (iffComp == null ||
                     ((flags & IFFFlags.Hide) == 0x0 &&
                      (flags & IFFFlags.HideLabel) == 0x0 &&
                      !hideLabelShuttle)) && // Lua decrypt mod + Lua alliesOnRadar
                    !gridObj.HideButton)
                {
                    _pendingMapObjects.Add((mapComp.MapId, gridObj));
                }
            }

            foreach (var (beacon, _) in _shuttles.GetExclusions(mapComp.MapId, _exclusions))
            {
                if (beacon.HideButton)
                    continue;

                _pendingMapObjects.Add((mapComp.MapId, beacon));
            }

            foreach (var (beacon, _) in _shuttles.GetBeacons(mapComp.MapId, _beacons))
            {
                if (beacon.HideButton)
                    continue;

                _pendingMapObjects.Add((mapComp.MapId, beacon));
            }

            HyperspaceDestinations.AddChild(mapButton);

            // Zoom in to our map
            if (mapComp.MapId == MapRadar.ViewingMap)
            {
                mapButton.BodyVisible = true;
            }
        }

        _pendingMapObjects.Sort((x, y) =>
        {
            var xKey = GetMapObjectSortKey(x.mapobj);
            var yKey = GetMapObjectSortKey(y.mapobj);
            return CompareMapObjectSortKeys(xKey, yKey);
        });

        foreach (var mapObj in _pendingMapObjects) // Lua
        {
            AddMapObject(mapObj.mapId, mapObj.mapobj); // Lua
        }
        _pendingMapObjects.Clear(); // Lua
    }

    private bool IsHiddenByNebulaVeil(EntityUid gridUid)
    {
        if (!_entManager.TryGetComponent(gridUid, out NebulaPresenceComponent? presence))
            return false;

        var prototypes = IoCManager.Resolve<IPrototypeManager>();
        if (presence.ActiveWeathers.Count == 0)
            return prototypes.TryIndex(presence.Weather, out NebulaWeatherPrototype? fallback) &&
                   fallback.Kind == NebulaWeatherKind.Veil;

        foreach (var weatherId in presence.ActiveWeathers)
        {
            if (prototypes.TryIndex(weatherId, out NebulaWeatherPrototype? weather) &&
                weather.Kind == NebulaWeatherKind.Veil)
                return true;
        }

        return false;
    }

