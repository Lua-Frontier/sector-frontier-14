using Content.Client._Lua.Styles;
using Content.Shared._Lua.Achievements;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Lua.Achievements;

[GenerateTypedNameReferences]
public sealed partial class AchievementToast : PanelContainer
{
    public AchievementToast()
    {
        RobustXamlLoader.Load(this);
        PanelOverride = LunaWindowStyle.Box(
            Color.FromHex("#0E1218EE"),
            LunaWindowStyle.Accent,
            1f);

        Header.FontOverride = LunaWindowStyle.FontTiny;
        Header.FontColorOverride = LunaWindowStyle.AccentGood;
        Title.FontOverride = LunaWindowStyle.FontTitle;
        Title.FontColorOverride = LunaWindowStyle.TextPrimary;
    }

    public void Setup(AchievementPrototype proto, SpriteSystem sprite)
    {
        var prototypes = IoCManager.Resolve<IPrototypeManager>();
        Icon.SetLayers(AchievementJobText.GetIconLayers(proto, prototypes), sprite);
        var title = AchievementJobText.GetName(proto, prototypes);
        Title.Text = title;
        if (title.Length > 22)
            Title.FontOverride = LunaWindowStyle.FontTiny;
        else if (title.Length > 15)
            Title.FontOverride = LunaWindowStyle.FontSmall;
        else
            Title.FontOverride = LunaWindowStyle.FontTitle;
    }
}
