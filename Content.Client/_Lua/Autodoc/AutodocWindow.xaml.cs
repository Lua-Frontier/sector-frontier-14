            "Head" => "health-analyzer-window-body-part-head",
            "Torso" => "health-analyzer-window-body-part-torso",
            "Groin" => "health-analyzer-window-body-part-groin",
            "LeftArm" => "health-analyzer-window-body-part-left-arm",
            "LeftHand" => "health-analyzer-window-body-part-left-hand",
            "RightArm" => "health-analyzer-window-body-part-right-arm",
