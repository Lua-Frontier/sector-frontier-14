    private void UpdateVitals(AutodocBoundUserInterfaceState state)
    {
        DiagnosticsContainer.DisposeAllChildren();
        if (!state.PatientPresent || state.Vitals is not { } vitals)
        {
            NameLabel.Text = string.Empty;
            SpeciesLabel.Text = string.Empty;
            StatusLabel.Text = string.Empty;
            TemperatureLabel.Text = string.Empty;
            BloodLabel.Text = string.Empty;
            DamageLabel.Text = string.Empty;
            BleedingLabel.Visible = false;
            return;
        }

        NameLabel.Text = vitals.Name;
        SpeciesLabel.Text = vitals.SpeciesId is { } speciesId && _prototypes.TryIndex<SpeciesPrototype>(speciesId, out var species)
            ? Loc.GetString(species.Name)
            : Loc.GetString("health-analyzer-window-entity-unknown-species-text");

        StatusLabel.Text = vitals.MobState switch
        {
            MobState.Alive => Loc.GetString("health-analyzer-window-entity-alive-text"),
            MobState.Critical => Loc.GetString("health-analyzer-window-entity-critical-text"),
            MobState.Dead => Loc.GetString("health-analyzer-window-entity-dead-text"),
            _ => Loc.GetString("health-analyzer-window-entity-unknown-text"),
        };

        TemperatureLabel.Text = !float.IsNaN(vitals.Temperature)
            ? $"{vitals.Temperature - Atmospherics.T0C:F1} °C"
            : Loc.GetString("health-analyzer-window-entity-unknown-value-text");

        BloodLabel.Text = !float.IsNaN(vitals.BloodLevel)
            ? $"{vitals.BloodLevel * 100:F0} %"
            : Loc.GetString("health-analyzer-window-entity-unknown-value-text");

        DamageLabel.Text = vitals.TotalDamage.ToString("0.#");
        BleedingLabel.Visible = vitals.Bleeding;

        DrawDiagnostics(state, vitals);
    }

    private void DrawDiagnostics(AutodocBoundUserInterfaceState state, AutodocPatientVitals vitals)
    {
        var selected = state.Parts.FirstOrDefault(part => part.Entity == state.SelectedPart);
        if (selected != null && vitals.SelectedPartDamage is { Count: > 0 } partDamage)
        {
            var partHeading = new Label
            {
                Text = Loc.GetString("autodoc-selected-part-damage", ("part", GetPartLabel(selected.Slot))),
            };
            LunaWindowStyle.StyleHeading(partHeading);
            DiagnosticsContainer.AddChild(partHeading);
            foreach (var (type, amount) in partDamage.OrderByDescending(entry => entry.Value))
            {
                var typeName = _prototypes.TryIndex<DamageTypePrototype>(type, out var proto)
                    ? proto.LocalizedName
                    : type;
                var typeLabel = new Label { Text = $" · {typeName}: {amount}" };
                LunaWindowStyle.StyleValue(typeLabel);
                DiagnosticsContainer.AddChild(typeLabel);
            }
        }

        foreach (var (groupId, amount) in vitals.DamagePerGroup.OrderByDescending(entry => entry.Value))
        {
            if (!_prototypes.TryIndex<DamageGroupPrototype>(groupId, out var group))
                continue;

            var groupLabel = new Label
            {
                Text = Loc.GetString("health-analyzer-window-damage-group-text",
                    ("damageGroup", group.LocalizedName),
                    ("amount", amount)),
                Margin = new Thickness(0, 4, 0, 0)
            };
            LunaWindowStyle.StyleHeading(groupLabel);
            DiagnosticsContainer.AddChild(groupLabel);

            foreach (var type in group.DamageTypes)
            {
                if (!vitals.DamagePerType.TryGetValue(type, out var typeAmount) || typeAmount <= FixedPoint2.Zero)
                    continue;

                var typeName = _prototypes.Index<DamageTypePrototype>(type).LocalizedName;
                var typeLabel = new Label
                {
                    Text = Loc.GetString("health-analyzer-window-damage-type-text",
                        ("damageType", typeName),
                        ("amount", typeAmount)).Insert(0, " · "),
                };
                LunaWindowStyle.StyleMuted(typeLabel);
                DiagnosticsContainer.AddChild(typeLabel);
            }
        }

        var damaged = vitals.DamagedParts
            .Select(part => new
            {
                Part = part,
                Total = part.Damage.Values.Aggregate(FixedPoint2.Zero, (sum, value) => sum + value)
            })
            .Where(part => part.Total > FixedPoint2.Zero)
            .OrderByDescending(part => part.Total)
            .Take(6)
            .ToList();

        if (damaged.Count == 0)
            return;

        var damagedTitle = new Label
        {
            Text = Loc.GetString("health-analyzer-window-damaged-parts-title"),
            Margin = new Thickness(0, 6, 0, 0)
        };
        LunaWindowStyle.StyleHeading(damagedTitle);
        DiagnosticsContainer.AddChild(damagedTitle);

        foreach (var entry in damaged)
        {
            var partLabel = new Label { Text = $"{GetPartLabel(entry.Part.Slot)}: {entry.Total}" };
            LunaWindowStyle.StyleValue(partLabel);
            DiagnosticsContainer.AddChild(partLabel);
            foreach (var (type, amount) in entry.Part.Damage.OrderByDescending(value => value.Value).Take(3))
            {
                var typeName = _prototypes.TryIndex<DamageTypePrototype>(type, out var proto)
                    ? proto.LocalizedName
                    : type;
                var typeLabel = new Label { Text = $" · {typeName}: {amount}" };
                LunaWindowStyle.StyleMuted(typeLabel);
                DiagnosticsContainer.AddChild(typeLabel);
            }
        }
    }

    private void BeginEntityDrag(NetEntity entity, DragSource source, GUIBoundKeyEventArgs args)
    {
        if (args.Function != EngineKeyFunctions.UIClick || _state?.Busy == true)
            return;
        BeginDrag(entity, source);
        args.Handle();
    }

    private void BeginDrag(NetEntity entity, DragSource source)
    {
        _dragSource = source;
        _dragMouseHeld = true;
        _dragHelper.MouseDown(entity);
    }

    private bool OnBeginDrag()
    {
        var entity = _dragHelper.Dragged;
        if (!_entities.TryGetEntity(entity, out var uid))
            return false;

        _dragShadow.SetEntity(uid);
        _dragShadow.Visible = true;
        UpdateDropTarget(entity);
        return true;
    }

    private bool OnContinueDrag(float frameTime)
    {
        LayoutContainer.SetPosition(_dragShadow, UserInterfaceManager.MousePositionScaled.Position - _dragShadow.Size / 2f);
        UpdateDropHover();
        return true;
    }

    private void OnEndDrag()
    {
        _dragShadow.Visible = false;
        _dragShadow.SetEntity(null);
        ClearDropTarget();
    }

    private void UpdateProgress()
    {
        if (_state is not { Busy: true } state)
            return;

        var progress = state.Progress;
        if (state.ProgressStart is { } start && state.ProgressEnd is { } end && end > start)
        {
            var elapsed = (_timing.CurTime - start).TotalSeconds;
            var duration = (end - start).TotalSeconds;
            progress = MathHelper.Lerp(state.Progress, state.ProgressTarget, (float) Math.Clamp(elapsed / duration, 0d, 1d));
        }

        ProgressBar.SetProgress(progress);
    }

    private void RebuildBody(AutodocBoundUserInterfaceState state)
    {
        if (!_entities.Deleted(_bodyViewEntity))
            _entities.QueueDeleteEntity(_bodyViewEntity);

        if (!state.PatientPresent)
        {
            PatientSprite.SetEntity(null);
            return;
        }

        _bodyViewEntity = _entities.Spawn(_bodyView);
        if (!_entities.TryGetComponent<SpriteComponent>(_bodyViewEntity, out var sprite))
            return;

        var status = new Dictionary<TargetBodyPart, TargetIntegrity>();
        foreach (var bodyPart in SharedTargetingSystem.GetValidParts())
        {
            var part = state.Parts.FirstOrDefault(value => value.Slot == bodyPart.ToString());
            status[bodyPart] = part == null
                ? TargetIntegrity.Severed
                : (TargetIntegrity) Math.Clamp((int) MathF.Ceiling((1f - part.Integrity) * 5f), 0, 5);
        }

        status[TargetBodyPart.Groin] = status.GetValueOrDefault(TargetBodyPart.Torso, TargetIntegrity.Severed);

        var layer = 0;
        foreach (var (bodyPart, integrity) in status)
        {
            var name = bodyPart.ToString().ToLowerInvariant();
            var rsi = new SpriteSpecifier.Rsi(
                new ResPath($"/Textures/_Shitmed/Interface/Targeting/Status/{name}.rsi"),
                $"{name}_{(int) integrity}");
            var texture = _sprites.Frame0(rsi);
            if (!sprite.TryGetLayer(layer, out _))
                sprite.AddLayer(texture);
            else
                sprite.LayerSetTexture(layer, texture);
            sprite.LayerSetScale(layer, new Vector2(6f, 6f));
            layer++;
        }

        PatientSprite.SetEntity(_bodyViewEntity);
    }

    private void UpdateDropTarget(NetEntity entity)
    {
        ClearDropTarget();

        switch (_dragSource)
        {
            case DragSource.BodyPart:
            case DragSource.Organ:
                SetPanelHighlight(StoragePanel, true);
                break;

            case DragSource.Storage:
            {
                var info = _state?.Storage.FirstOrDefault(value => value.Entity == entity);
                if (info == null)
                    return;

                if (info.BodyPartSlot != null)
                {
                    SetPanelHighlight(DollPanel, true);
                    HighlightAttachSlot(info.BodyPartSlot);
                }
                else if (info.OrganSlot != null)
                {
                    SetPanelHighlight(OrganPanel, true);
                    if (_selectedPart != null)
                    {
                        var selected = _state?.Parts.FirstOrDefault(part => part.Entity == _selectedPart);
                        if (selected != null && _partButtons.TryGetValue(selected.Slot, out var partButton))
                            SetPartHighlight(selected.Slot, partButton);
                    }
                }

                break;
            }
        }

        UpdateDropHover();
    }

    private void UpdateDropHover()
    {
        if (!_dragHelper.IsDragging)
            return;

        var mouse = UserInterfaceManager.MousePositionScaled.Position;
        switch (_dragSource)
        {
            case DragSource.BodyPart:
            case DragSource.Organ:
                StoragePanel.ModulateSelfOverride = StoragePanel.GlobalRect.Contains(mouse)
                    ? DropBorder
                    : null;
                break;
            case DragSource.Storage:
                var info = _state?.Storage.FirstOrDefault(value => value.Entity == _dragHelper.Dragged);
                if (info?.BodyPartSlot != null)
                {
                    DollPanel.ModulateSelfOverride = BodyDoll.GlobalRect.Contains(mouse)
                        ? DropBorder
                        : null;
                }
                else if (info?.OrganSlot != null)
                {
                    OrganPanel.ModulateSelfOverride = OrganPanel.GlobalRect.Contains(mouse)
                        ? DropBorder
                        : null;
                }

                break;
        }
    }

    private void HighlightAttachSlot(string? partSlot)
    {
        var targetSlot = partSlot switch
        {
            "Head" or "LeftArm" or "RightArm" or "LeftLeg" or "RightLeg" => "Torso",
            "LeftHand" => "LeftArm",
            "RightHand" => "RightArm",
            "LeftFoot" => "LeftLeg",
            "RightFoot" => "RightLeg",
            _ => null
        };

        if (targetSlot != null && _partButtons.TryGetValue(targetSlot, out var target))
            SetPartHighlight(targetSlot, target);

        if (targetSlot is "Torso")
        {
            _highlightGroin = true;
            GroinButton.TextureNormal = _resources.GetTexture(GroinHoverTexture);
            GroinButton.ModulateSelfOverride = DropBorder;
        }
    }

    private void SetPartHighlight(string slot, TextureButton button)
    {
        _highlightedPart = button;
        if (PartHoverTextures.TryGetValue(slot, out var path))
            button.TextureNormal = _resources.GetTexture(path);
        button.ModulateSelfOverride = DropBorder;
    }

    private void SetPanelHighlight(PanelContainer panel, bool highlight)
    {
        panel.PanelOverride = highlight ? _panelHighlight : null;
    }

    private void ClearDropTarget()
    {
        SetPanelHighlight(DollPanel, false);
        SetPanelHighlight(OrganPanel, false);
        SetPanelHighlight(StoragePanel, false);
        DollPanel.ModulateSelfOverride = null;
        OrganPanel.ModulateSelfOverride = null;
        StoragePanel.ModulateSelfOverride = null;

        if (_highlightedPart != null)
        {
            _highlightedPart.TextureNormal = null;
            _highlightedPart.ModulateSelfOverride = null;
            _highlightedPart = null;
        }

        if (_highlightGroin)
        {
            GroinButton.TextureNormal = null;
            GroinButton.ModulateSelfOverride = null;
            _highlightGroin = false;
        }

        foreach (var button in _partButtons.Values)
        {
