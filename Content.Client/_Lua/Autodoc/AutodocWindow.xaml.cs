    protected override void EnteredTree()
    {
        base.EnteredTree();
        if (_dragShadow.Parent == null)
            UserInterfaceManager.PopupRoot.AddChild(_dragShadow);
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _dragMouseHeld = false;
        _dragHelper.EndDrag();
        _dragShadow.Orphan();
        if (!_entities.Deleted(_bodyViewEntity))
            _entities.QueueDeleteEntity(_bodyViewEntity);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateProgress();
        _dragHelper.Update(args.DeltaSeconds);
        if (!_dragMouseHeld || _input.IsKeyDown(Key.MouseLeft))
            return;

        _dragMouseHeld = false;
        var dragged = _dragHelper.Dragged;
        var mouse = UserInterfaceManager.MousePositionScaled.Position;
        if (_dragHelper.IsDragging && dragged is { } item)
        {
            if (_dragSource is DragSource.BodyPart or DragSource.Organ && StoragePanel.GlobalRect.Contains(mouse))
            {
                var source = _dragSource == DragSource.BodyPart ? AutodocTransferTarget.BodyPart : AutodocTransferTarget.OrganSlot;
                OnTransfer?.Invoke(new AutodocTransferMessage(item, source, AutodocTransferTarget.Storage, _selectedPart));
            }
            else if (_dragSource == DragSource.Storage && BodyDoll.GlobalRect.Contains(mouse))
            {
                OnTransfer?.Invoke(new AutodocTransferMessage(item, AutodocTransferTarget.Storage, AutodocTransferTarget.BodyPart, _selectedPart));
            }
            else if (_dragSource == DragSource.Storage && OrganPanel.GlobalRect.Contains(mouse) &&
                     _state?.Storage.FirstOrDefault(value => value.Entity == item)?.OrganSlot is { } organSlot)
            {
                OnTransfer?.Invoke(new AutodocTransferMessage(item, AutodocTransferTarget.Storage,
                    AutodocTransferTarget.OrganSlot, _selectedPart, organSlot));
            }
        }

        _dragSource = DragSource.None;
        _dragHelper.EndDrag();
    }

    public void UpdateState(AutodocBoundUserInterfaceState state)
    {
        _state = state;
        _selectedPart = state.SelectedPart;
        NoPatientLabel.Visible = !state.PatientPresent;
        PatientContent.Visible = state.PatientPresent;
        BusyOverlay.Visible = state.Busy;
        BusyLabel.Text = state.Status;
        UpdateProgress();

        foreach (var (slot, button) in _partButtons)
        {
            button.Visible = state.PatientPresent;
            button.Disabled = state.Busy || state.Parts.All(part => part.Slot != slot);
        }

        GroinButton.Visible = state.PatientPresent;
        GroinButton.Disabled = state.Busy || state.Parts.All(part => part.Slot != "Torso");

        RebuildBody(state);
        UpdateVitals(state);

        var selected = state.Parts.FirstOrDefault(part => part.Entity == state.SelectedPart);
        SelectedPartLabel.Text = selected != null
            ? Loc.GetString("autodoc-selected-part", ("part", GetPartLabel(selected.Slot)))
            : Loc.GetString("autodoc-select-part");
        HealButton.Disabled = selected == null || state.Busy;
        RemoveButton.Disabled = selected == null || state.Busy;
        RebuildOrgans(state);
        RebuildStorage(state);
    }

