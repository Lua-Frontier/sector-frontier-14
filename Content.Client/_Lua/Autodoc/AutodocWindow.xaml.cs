    private void BeginPartDrag(string slot, GUIBoundKeyEventArgs args)
    {
        if (args.Function != EngineKeyFunctions.UIClick || _state?.Busy == true)
            return;
        var part = _state?.Parts.FirstOrDefault(value => value.Slot == slot);
        if (part == null)
            return;
        BeginDrag(part.Entity, DragSource.BodyPart);
        args.Handle();
    }

    private void RebuildOrgans(AutodocBoundUserInterfaceState state)
    {
        OrganList.DisposeAllChildren();
        foreach (var organ in state.Organs)
        {
            var row = CreateListRow(
                organ.Name ?? Loc.GetString("autodoc-organ-empty"),
                organ.Entity is { } iconEntity && _entities.TryGetEntity(iconEntity, out var organUid)
                    ? organUid
                    : null);

            if (organ.Entity is { } entity)
                row.OnKeyBindDown += args => BeginEntityDrag(entity, DragSource.Organ, args);

            OrganList.AddChild(row);
        }
    }

    private void RebuildStorage(AutodocBoundUserInterfaceState state)
    {
        StorageList.DisposeAllChildren();
        foreach (var item in state.Storage)
        {
            var label = item.BodyPartSlot != null
                ? GetPartLabel(item.BodyPartSlot)
                : item.Name;

            var row = CreateListRow(
                label,
                _entities.TryGetEntity(item.Entity, out var entity) ? entity : null);

            row.OnKeyBindDown += args => BeginEntityDrag(item.Entity, DragSource.Storage, args);
            StorageList.AddChild(row);
        }
    }

